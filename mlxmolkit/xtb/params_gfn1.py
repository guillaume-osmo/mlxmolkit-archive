@dataclass(frozen=True)
class GFN1Shell:
    """One shell on a GFN1 element."""
    l: int                # angular momentum
    n: int                # principal quantum number
    h: float              # bare level energy (eV)
    zeta: float           # Slater exponent
    k_poly: float         # shellPoly per-l-per-Z (eV-scale)
    shell_hardness: float # shellHardness scaling


@dataclass(frozen=True)
class GFN1ElementParams:
    """Per-element block for GFN1."""
    Z: int
    symbol: str
    shells: tuple[GFN1Shell, ...]
    en: float                     # Pauling electronegativity (gfn1.f90 uses paulingEN)
    chemical_hardness: float      # GAM
    third_order: float            # thirdOrderAtom (already × 0.1)
    rep_alpha: float              # REPA
    rep_zeff: float               # REPB
    halogen_bond: float           # halogenBond strength (only nonzero for halogens)


_ELEMENT_SYMBOLS = (
    "H","He","Li","Be","B","C","N","O","F","Ne",
    "Na","Mg","Al","Si","P","S","Cl","Ar","K","Ca",
    "Sc","Ti","V","Cr","Mn","Fe","Co","Ni","Cu","Zn",
    "Ga","Ge","As","Se","Br","Kr","Rb","Sr","Y","Zr",
    "Nb","Mo","Tc","Ru","Rh","Pd","Ag","Cd","In","Sn",
    "Sb","Te","I","Xe","Cs","Ba","La","Ce","Pr","Nd",
    "Pm","Sm","Eu","Gd","Tb","Dy","Ho","Er","Tm","Yb",
    "Lu","Hf","Ta","W","Re","Os","Ir","Pt","Au","Hg",
    "Tl","Pb","Bi","Po","At","Rn",
)
assert len(_ELEMENT_SYMBOLS) == 86


def _build_element(Z: int) -> GFN1ElementParams:
    n_sh = _GFN1_NSHELL[Z]
    shells = []
    for ish in range(n_sh):
        l = _GFN1_ANGSHELL[Z][ish]
        n = _GFN1_PRINCIPALQUANTUMNUMBER[Z][ish]
        h = _GFN1_SELFENERGY[Z][ish]
        zeta = _GFN1_SLATEREXPONENT[Z][ish]
        k_poly = _GFN1_SHELLPOLY[Z][l]   # per-l (not per-shell-index)
        sh_hard = _GFN1_SHELLHARDNESS[Z][l]
        shells.append(GFN1Shell(
            l=int(l), n=int(n), h=float(h), zeta=float(zeta),
            k_poly=float(k_poly), shell_hardness=float(sh_hard),
        ))
    return GFN1ElementParams(
        Z=Z,
        symbol=_ELEMENT_SYMBOLS[Z - 1],
        shells=tuple(shells),
        en=float(_GFN1_PAULING_EN[Z]),
        chemical_hardness=float(_GFN1_CHEMICALHARDNESS[Z]),
        third_order=float(_GFN1_THIRDORDERATOM[Z]),
        rep_alpha=float(_GFN1_REPALPHA[Z]),
        rep_zeff=float(_GFN1_REPZEFF[Z]),
        halogen_bond=float(_GFN1_HALOGENBOND[Z]),
    )


GFN1_PARAMS: dict[int, GFN1ElementParams] = {Z: _build_element(Z) for Z in range(1, 87)}
